function tripStamp(t) {
  return (t.datetime || t.date + "T00:00").replace("T", " ");
}

/* Average Turnaround Time (hours) between consecutive completed trips in a list.
 * The turnaround cycle is split into:
 *   loaded   = loaded km ÷ loaded speed (25 km/h)
 *   unloaded = empty km ÷ empty speed (45 km/h)
 *   idle     = remaining turnaround time (loading, unloading, waiting)
 * Driving is limited to 9 hours per day, so legs longer than 9 h span multiple days.
 */
const LOADED_AVG_KMH = 25;
const EMPTY_AVG_KMH = 45;
const DRIVING_HOURS_PER_DAY = 9;

function tripDriving(t) {
  const km = Number(t.km) || 0;
  const empty = Math.min(Number(t.emptyKm) || 0, km);
  const loaded = km - empty;
  const loadedH = loaded / LOADED_AVG_KMH;
  const unloadedH = empty / EMPTY_AVG_KMH;
  return { loaded: loadedH, unloaded: unloadedH, days: Math.max(1, Math.ceil((loadedH + unloadedH) / DRIVING_HOURS_PER_DAY)) };
}

function avgTurnaround(tripList) {
  const sorted = tripList.slice().sort((a, b) => (tripStamp(a) < tripStamp(b) ? -1 : 1));
  let tGap = 0, tLoad = 0, tEmpty = 0, tDays = 0, n = 0;
  for (let i = 1; i < sorted.length; i++) {
    const diff = new Date(tripStamp(sorted[i]).replace(" ", "T")) - new Date(tripStamp(sorted[i - 1]).replace(" ", "T"));
    if (isFinite(diff) && diff > 0) {
      const drv = tripDriving(sorted[i - 1]);
      tGap += diff / 3600000;
      tLoad += drv.loaded;
      tEmpty += drv.unloaded;
      tDays += drv.days;
      n += 1;
    }
  }
  if (!n) return null;
  const tat = tGap / n;
  const loaded = tLoad / n;
  const unloaded = tEmpty / n;
  return { tat, loaded, unloaded, idle: Math.max(0, tat - loaded - unloaded), days: tDays / n };
}

function performanceStats(from, to) {
  const done = getTrips().filter((t) => t.status === "completed");
  const inRange = (from || to)
    ? done.filter((t) => (!from || t.date >= from) && (!to || t.date <= to))
    : done;
  const veh = {};
  const drv = {};
  inRange.forEach((t) => {
    const km = Number(t.km) || 0;
    const empty = Math.min(Number(t.emptyKm) || 0, km);
    const loadKm = km - empty;
    const weight = Number(t.weight) || 0;
    if (!veh[t.vehiclePlate]) veh[t.vehiclePlate] = { key: t.vehiclePlate, trips: 0, loadKm: 0, emptyKm: 0, tonKm: 0, tons: 0, tripList: [] };
    const v = veh[t.vehiclePlate];
    v.trips += 1; v.loadKm += loadKm; v.emptyKm += empty; v.tonKm += weight * loadKm; v.tons += weight; v.tripList.push(t);
    if (!drv[t.driverId]) drv[t.driverId] = { key: t.driverId, trips: 0, loadKm: 0, emptyKm: 0, tonKm: 0, tons: 0, tripList: [] };
    const d = drv[t.driverId];
    d.trips += 1; d.loadKm += loadKm; d.emptyKm += empty; d.tonKm += weight * loadKm; d.tons += weight; d.tripList.push(t);
  });
  Object.keys(veh).forEach((k) => {
    veh[k].totalKm = veh[k].loadKm + veh[k].emptyKm;
    veh[k].factor = veh[k].totalKm ? (veh[k].loadKm / veh[k].totalKm) * 100 : 0;
    const tat = avgTurnaround(veh[k].tripList);
    veh[k].avgTat = tat ? tat.tat : null;
    veh[k].tatLoaded = tat ? tat.loaded : null;
    veh[k].tatUnloaded = tat ? tat.unloaded : null;
    veh[k].tatIdle = tat ? tat.idle : null;
    veh[k].tatDays = tat ? tat.days : null;
    delete veh[k].tripList;
  });
  Object.keys(drv).forEach((k) => {
    drv[k].totalKm = drv[k].loadKm + drv[k].emptyKm;
    drv[k].factor = drv[k].totalKm ? (drv[k].loadKm / drv[k].totalKm) * 100 : 0;
    const tat = avgTurnaround(drv[k].tripList);
    drv[k].avgTat = tat ? tat.tat : null;
    drv[k].tatLoaded = tat ? tat.loaded : null;
    drv[k].tatUnloaded = tat ? tat.unloaded : null;
    drv[k].tatIdle = tat ? tat.idle : null;
    drv[k].tatDays = tat ? tat.days : null;
    delete drv[k].tripList;
  });
  return { vehicles: Object.values(veh), drivers: Object.values(drv) };
}

