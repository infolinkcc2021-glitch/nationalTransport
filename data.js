function fmtTat(hours) {
  if (hours == null || !isFinite(hours)) return "—";
  if (hours < 1) return Math.round(hours * 60) + "m";
  const h = Math.floor(hours);
  const m = Math.round((hours - h) * 60);
  return m ? h + "h " + String(m).padStart(2, "0") + "m" : h + "h";
}

